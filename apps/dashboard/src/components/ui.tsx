/* -------------------------------------------------------------- Badge */

const badgeVariants = cva(
  "inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-medium",
  {
    variants: {
      variant: {
        default: "bg-muted text-foreground",
        success: "bg-success/15 text-success",
        warning: "bg-warning/15 text-warning",
        destructive: "bg-destructive/15 text-destructive",
        info: "bg-info/15 text-info",
        outline: "border border-border text-muted-foreground",
      },
    },
    defaultVariants: { variant: "default" },
  },
);

export function Badge({
  className,
  variant,
  ...props
}: React.HTMLAttributes<HTMLSpanElement> & VariantProps<typeof badgeVariants>) {
  return <span className={cn(badgeVariants({ variant }), className)} {...props} />;
}

const STATUS_MAP: Record<string, { variant: VariantProps<typeof badgeVariants>["variant"]; label: string }> = {
  running: { variant: "success", label: "Running" },
  success: { variant: "success", label: "Success" },
  deployed: { variant: "success", label: "Deployed" },
  idle: { variant: "outline", label: "Idle" },
  stopped: { variant: "warning", label: "Stopped" },
  exited: { variant: "warning", label: "Exited" },
  created: { variant: "info", label: "Created" },
  queued: { variant: "info", label: "Queued" },
  deploying: { variant: "info", label: "Deploying" },
  pending: { variant: "warning", label: "Pending" },
  issued: { variant: "success", label: "Issued" },
  expiring: { variant: "warning", label: "Expiring" },
  disabled: { variant: "outline", label: "Disabled" },
  failed: { variant: "destructive", label: "Failed" },
  error: { variant: "destructive", label: "Error" },
  cancelled: { variant: "outline", label: "Cancelled" },
  timed_out: { variant: "destructive", label: "Timed out" },
  unknown: { variant: "outline", label: "Unknown" },
};

export function StatusBadge({ status, className }: { status: string; className?: string }) {
  const mapped = STATUS_MAP[status] ?? { variant: "outline" as const, label: status };
  return (
    <Badge variant={mapped.variant} className={className}>
      <span
        className={cn(
          "h-1.5 w-1.5 rounded-full",
          mapped.variant === "success" && "bg-success",
          mapped.variant === "warning" && "bg-warning",
          mapped.variant === "destructive" && "bg-destructive",
          mapped.variant === "info" && "bg-info animate-pulse",
          mapped.variant === "outline" && "bg-muted-foreground",
        )}
      />
      {mapped.label}
    </Badge>
  );
}

/* -------------------------------------------------------------- Dialog */

export function Dialog({
  open,
  onClose,
  title,
  description,
  children,
  footer,
  wide,
}: {
  open: boolean;
  onClose: () => void;
  title: string;
  description?: string;
  children: React.ReactNode;
  footer?: React.ReactNode;
  wide?: boolean;
}) {
  React.useEffect(() => {
    const handler = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    if (open) window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [open, onClose]);

  if (!open) return null;
  return (
    <div className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-black/60 p-4 pt-[8vh] backdrop-blur-sm">
      <div
        className={cn(
          "relative w-full rounded-xl border border-border bg-card shadow-2xl",
          wide ? "max-w-3xl" : "max-w-lg",
        )}
        role="dialog"
        aria-modal="true"
      >
        <div className="flex items-start justify-between border-b border-border p-5 pb-4">
          <div>
            <h2 className="text-lg font-semibold">{title}</h2>
            {description && <p className="mt-1 text-sm text-muted-foreground">{description}</p>}
          </div>
          <button onClick={onClose} className="rounded-lg p-1 text-muted-foreground hover:bg-muted" aria-label="Close">
            <X className="h-4 w-4" />
          </button>
        </div>
        <div className="p-5">{children}</div>
        {footer && <div className="flex justify-end gap-2 border-t border-border p-4">{footer}</div>}
      </div>
    </div>
  );
}

export function ConfirmDialog({
  open,
  onClose,
  onConfirm,
  title,
  message,
  confirmLabel = "Delete",
  destructive = true,
}: {
  open: boolean;
  onClose: () => void;
  onConfirm: () => void;
  title: string;
  message: string;
  confirmLabel?: string;
  destructive?: boolean;
}) {
  return (
    <Dialog
      open={open}
      onClose={onClose}
      title={title}
      footer={
        <>
          <Button variant="outline" onClick={onClose}>Cancel</Button>
          <Button
            variant={destructive ? "destructive" : "default"}
            onClick={() => {
              onConfirm();
              onClose();
            }}
          >
            {confirmLabel}
          </Button>
        </>
      }
    >
      <p className="text-sm text-muted-foreground">{message}</p>
    </Dialog>
  );
}

